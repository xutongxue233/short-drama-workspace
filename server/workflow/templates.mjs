export function createApproval(project, node) {
  if (node.id === "characters" && node.characterGeneration?.stage === "pilot")
    return {
      id: uid("approval"),
      nodeId: node.id,
      kind: "character",
      phase: "character-pilot",
      title: `确认「${node.characterGeneration.pilotName}」基础角色样板`,
      description:
        "请先检查画风、五官、完整身形和固定服装。采用样板后继续制作本集其余角色，全部角色仍需逐一验收，尚不进入分镜。",
      nextStep: { name: "其余角色基础图", agentId: node.agentId },
    };
  const configs = {
    analysis: [
      "style",
      "确认本集制作方案",
      "本次原文用于制作一集，无需预设全剧集数。已填好时长、画幅与平台建议值，已选风格直接沿用；确认后编剧自动创作本集剧本，在下一处人工确认节点暂停。",
      STYLES,
    ],
    adaptation: [
      "script",
      "确认改编剧本提案",
      "请检查原著覆盖、人物动机、冲突和悬念。缺失章节与改编增补应明确标注；确认后进入内容自查。",
    ],
    characters: [
      "character",
      "确认并锁定角色资产",
      "检查每张角色卡的姓名、身份、外貌与服装。确认后这些角色资产会被锁定，供后续每个镜头引用。",
    ],
    storyboard: [
      "storyboard",
      "确认分镜与镜头节奏",
      "检查镜头顺序、对白、角色引用和动作连续性。确认后锁定分镜并进入视频制作。",
    ],
    delivery: [
      "delivery",
      "确认制作资料包交付",
      "请核对产物清单与待制作事项。未制作的镜头与剪辑应明确列出；交付包可随时导出为 JSON。",
    ],
  };
  const config = configs[node.id];
  if (!config) return null;
  const [kind, title, description, options] = config;
  const next =
    project.nodes[project.nodes.findIndex((item) => item.id === node.id) + 1];
  return {
    id: uid("approval"),
    nodeId: node.id,
    kind,
    title,
    description,
    ...(options ? { options } : {}),
    ...(node.id === "analysis" ? { fields: briefFields(project) } : {}),
    ...(next ? { nextStep: { name: next.name, agentId: next.agentId } } : {}),
  };
}
